#!/bin/bash
# PreToolUse hook: blocks Claude from editing package-lock.json directly.
# Reads the tool call as JSON on stdin; exit 2 blocks the call and shows stderr to Claude.

INPUT=$(cat)

# Extract tool_input.file_path without jq (not installed on every machine).
# Windows paths arrive JSON-escaped (D:\\AI-TRAINING\\...), which the suffix match below still handles.
FILE_PATH=$(printf '%s' "$INPUT" | tr -d '\r\n' |
  sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')

if [[ "$FILE_PATH" == *package-lock.json ]]; then
  echo "Blocked: $FILE_PATH is generated by npm. Run npm install instead of editing it." >&2
  exit 2
fi

exit 0
